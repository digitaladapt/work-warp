<?php

declare(strict_types=1);

namespace App\Stack;

/**
 * A filesystem mount a service requests: a *named volume* of the stack, or a
 * relative path inside a named volume — never a host path.
 *
 * This is the stack's equivalent of `ContainerSpec`'s single computed bind,
 * and its whole security argument is in what it cannot say. There is no field
 * for a host path, no way to name the daemon socket, no `source` that is not
 * `SessionName`-derived. `type: bind` is not "validated away" — it is not a
 * value the type can hold, because `source` is a `StackVolumeName` and a
 * `StackVolumeName` cannot be `/var/run/docker.sock`.
 *
 * Compose's short syntax `./src:/app/src` is therefore *not* expressible in
 * this vocabulary — and saying so plainly matters more than supporting it:
 * a caller that needs host files has the workspace, and the workspace is
 * mounted into every *command* container, not into stack services. If a stack
 * needs the workspace's contents, the shape to reach for is to build an image
 * from them (`POST /build`) and run that — which is the workflow PLAN.md §6.1
 * already prescribes.
 */
final class StackVolumeName
{
    /**
     * A named volume within the stack: `ww-stk-<session>-<name>`.
     *
     * Lowercase segments with interior `-`/`_`/`.`, the same length ceiling as
     * a session name's derived names, and the `ww-` prefix is generated by
     * `SessionName` — never supplied — so a caller cannot aim at a volume by
     * typing its name. (Ownership is still decided by labels; the name exists
     * so `docker volume ls` is readable.)
     */
    private const string PATTERN = '/^[a-z0-9][a-z0-9._-]{0,38}\z/';

    private function __construct(public readonly string $value)
    {
    }

    public static function from(string $name): self
    {
        if (1 !== preg_match(self::PATTERN, $name)) {
            throw InvalidStackRequest::because(\sprintf('volume names must match %s (lowercase letters, digits, dots, dashes and underscores, at most 39 characters), got "%s"', self::PATTERN, $name));
        }

        return new self($name);
    }
}
